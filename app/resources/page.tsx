import { uploadDocument } from "@/lib/actions";
import { getCourses, getDocuments, getDocumentNotes, getDocumentQuestions } from "@/lib/db";
import { buildVideoRecommendations } from "@/lib/pdf";
import { DocumentReader } from "@/components/document-reader";

export default async function ResourcesPage() {
  const courses = getCourses();
  const documents = getDocuments();

  return (
    <div className="space-y-8">
      <header>
        <p className="text-xs uppercase tracking-[0.24em] text-violet-300">Resources</p>
        <h2 className="mt-2 text-3xl font-semibold text-white">Smart document reader</h2>
        <p className="mt-2 max-w-2xl text-sm leading-6 text-slate-400">
          Read extracted PDF text, ask questions grounded in the source, and create notes you can edit and keep.
          Everything runs locally; answers are matched to document passages rather than generated by an external AI service.
        </p>
      </header>

      <section className="card rounded-3xl p-5">
        <h3 className="text-lg font-semibold text-white">Upload lecture notes or PDF</h3>
        <form action={uploadDocument} className="mt-4 grid gap-3 md:grid-cols-[1fr_1fr_auto]" encType="multipart/form-data">
          <select name="course_id" className="rounded-xl border border-white/10 bg-slate-950/60 px-3 py-2 text-white" required>
            <option value="">Choose a course</option>
            {courses.map((course) => (
              <option key={course.id} value={course.id}>{course.name}</option>
            ))}
          </select>
          <input type="file" name="file" accept="application/pdf" className="rounded-xl border border-dashed border-white/15 bg-slate-950/60 p-2 text-sm text-slate-300" required />
          <button type="submit" className="rounded-full bg-violet-500 px-4 py-2 font-semibold text-white hover:bg-violet-400">Upload</button>
        </form>
      </section>

      <section className="grid gap-6 xl:grid-cols-2">
        {documents.length === 0 ? (
          <div className="card rounded-3xl p-5 text-sm text-slate-300">No uploaded documents yet. Add a PDF to generate a topic checklist and summaries.</div>
        ) : (
          documents.map((document) => {
            const questions = getDocumentQuestions(document.id);
            const notes = getDocumentNotes(document.id)?.notes || "";
            const documentName = document.file_name.replace(/\.[^.]+$/, "");
            const youtubeQuery = encodeURIComponent(`${documentName} study guide`);
            const generalQuery = encodeURIComponent(`${documentName} educational resources`);
            const recommendedVideos = buildVideoRecommendations(document.extracted_text || document.summary || document.file_name, documentName);
            return (
              <article key={document.id} className="card rounded-3xl p-5">
                <div className="flex items-center justify-between gap-3">
                  <div className="min-w-0">
                    <p className="text-xs uppercase tracking-[0.2em] text-violet-300">Document</p>
                    <h3 className="mt-2 truncate text-xl font-semibold text-white">{document.file_name}</h3>
                  </div>
                  <span className="shrink-0 rounded-full border border-white/10 px-2 py-1 text-xs uppercase tracking-[0.2em] text-slate-300">{document.status}</span>
                </div>

                <p className="mt-3 text-sm leading-6 text-slate-400">
                  {document.summary || "The PDF could not be summarized. Scanned pages may need OCR before they can be read."}
                </p>

                <DocumentReader
                  documentId={document.id}
                  fileName={documentName}
                  extractedText={document.extracted_text || ""}
                  notes={notes}
                  questions={questions}
                />

                <div className="mt-5">
                  <h4 className="text-xs font-semibold uppercase tracking-[0.2em] text-slate-400">Video recommendations from this document</h4>
                  <div className="mt-3 flex flex-wrap gap-2">
                    {recommendedVideos.map((video) => (
                      <a key={video.url} href={video.url} target="_blank" rel="noreferrer" className="rounded-full border border-violet-500/30 bg-violet-500/10 px-3 py-2 text-xs text-violet-200 hover:bg-violet-500/20">
                        {video.title}
                      </a>
                    ))}
                  </div>
                  <div className="mt-3 flex flex-wrap gap-2 text-xs">
                    <a href={`https://www.youtube.com/results?search_query=${youtubeQuery}`} target="_blank" rel="noreferrer" className="rounded-full border border-white/10 px-3 py-1.5 text-slate-300 hover:text-white">YouTube search</a>
                    <a href={`https://scholar.google.com/scholar?q=${generalQuery}`} target="_blank" rel="noreferrer" className="rounded-full border border-white/10 px-3 py-1.5 text-slate-300 hover:text-white">Academic search</a>
                    <a href={`https://www.google.com/search?q=${generalQuery}`} target="_blank" rel="noreferrer" className="rounded-full border border-white/10 px-3 py-1.5 text-slate-300 hover:text-white">Article search</a>
                  </div>
                </div>
              </article>
            );
          })
        )}
      </section>
    </div>
  );
}
